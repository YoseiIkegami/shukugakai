export function pick<T>(items: T[], index: number) {
  return items[((index % items.length) + items.length) % items.length]!;
}

export function programmeNumber(sequence: number) {
  return `第${String(sequence).padStart(4, "0")}回`;
}

export function broadcastDate(date = new Date()) {
  return new Intl.DateTimeFormat("ja-JP", { year: "numeric", month: "long", day: "numeric" }).format(date);
}

export function nextStage(stage: BroadcastStage): BroadcastStage {
  const order: BroadcastStage[] = ["standby", "headline", "praise", "ceremony", "ticket"];
  return order[Math.min(order.indexOf(stage) + 1, order.length - 1)]!;
}
